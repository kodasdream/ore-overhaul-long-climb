/// What stays as it is, so a player can reach the 5x5 table at all.
fn early(result: &str) -> bool {
    if result.ends_with("_planks") || matches!(result, "minecraft:stick" | "minecraft:crafting_table" | "longclimb:crafting_table_5x5") {
        return true;
    }
    let Some(name) = result.strip_prefix("minecraft:") else { return false };
    ["wooden_", "stone_"].iter().any(|tier| {
        name.strip_prefix(tier).is_some_and(|kind| matches!(kind, "pickaxe" | "axe" | "shovel" | "hoe" | "sword"))
    })
}

fn trimmed(pattern: &[Value]) -> Vec<Vec<char>> {
    let rows: Vec<Vec<char>> = pattern.iter().filter_map(|r| r.as_str().map(|s| s.chars().collect())).collect();
    let width = rows.iter().map(Vec::len).max().unwrap_or(0);
    let filled = |x: usize| rows.iter().any(|r| r.get(x).is_some_and(|c| *c != ' '));
    let (Some(left), Some(right)) = ((0..width).find(|x| filled(*x)), (0..width).rev().find(|x| filled(*x))) else {
        return Vec::new();
    };
    let has = |r: &Vec<char>| r.iter().any(|c| *c != ' ');
    let (Some(top), Some(bottom)) = (rows.iter().position(has), rows.iter().rposition(has)) else {
        return Vec::new();
    };
    rows[top..=bottom].iter().map(|r| (left..=right).map(|x| r.get(x).copied().unwrap_or(' ')).collect()).collect()
}

/// Where each source row or column lands in the bigger grid; the rows and columns between are filled in (`grow`). A pair grows
/// to three when the other side grows to five (that is wide enough), else to four.
fn anchors(from: usize, other: usize) -> (usize, Vec<usize>) {
    match (from, other) {
        (3, _) => (5, vec![0, 2, 4]),
        (2, 3) => (3, vec![0, 2]),
        (2, _) => (4, vec![0, 3]),
        _ => (1, vec![0]),
    }
}

/// A cell between two others: the same ingredient when both are, the one the recipe uses more when they differ (a cake's
/// sugar beside its egg), and empty next to an empty cell, so outlines and holes keep their shape.
fn between(a: char, b: char, uses: &[(char, usize)]) -> char {
    let n = |c: char| uses.iter().find(|(k, _)| *k == c).map_or(0, |(_, n)| *n);
    match (a, b) {
        (' ', _) | (_, ' ') => ' ',
        (x, y) if x == y => x,
        (x, y) => if n(y) > n(x) { y } else { x },
    }
}

/// The recipe drawn bigger, keeping its shape: a chest's ring stays a ring, a bucket becomes a V, a rail a track.
fn grow(rows: &[Vec<char>], uses: &[(char, usize)]) -> Vec<String> {
    let (h, w) = (rows.len(), rows[0].len());
    // Single cells and single lines become a line of four or five, so nothing fits a 3x3 any more.
    let ((tw, cols), (th, lines)) = match (w, h) {
        (1, 1) => ((1, vec![0]), (4, vec![0, 3])),
        _ => (anchors(w, h), anchors(h, w)),
    };
    let mut g = vec![vec![' '; tw]; th];
    for (sy, &ty) in lines.iter().enumerate() {
        for (sx, &tx) in cols.iter().enumerate() {
            g[ty][tx] = rows[sy.min(h - 1)][sx.min(w - 1)];
        }
    }
    // A lone ingredient stretched into a line: the copies join up.
    if w == 1 && h == 1 {
        for row in g.iter_mut() {
            row[0] = rows[0][0];
        }
    }
    // Fill between the placed cells along each row, then along each column.
    for &ty in &lines {
        for pair in cols.windows(2) {
            for x in pair[0] + 1..pair[1] {
                g[ty][x] = between(g[ty][pair[0]], g[ty][pair[1]], uses);
            }
        }
    }
    for x in 0..tw {
        for pair in lines.windows(2) {
            for y in pair[0] + 1..pair[1] {
                g[y][x] = between(g[pair[0]][x], g[pair[1]][x], uses);
            }
        }
    }
    // Diagonals: two neighbouring cells of the same ingredient on a diagonal are joined by a line through the empty cells
    // between them (a bucket's V, a hopper's funnel, shears' blades).
    let placed = g.clone();
    for (iy, &ya) in lines.iter().enumerate().take(lines.len().saturating_sub(1)) {
        let yb = lines[iy + 1];
        for (ix, &xa) in cols.iter().enumerate() {
            for xb in [ix.checked_sub(1).map(|i| cols[i]), cols.get(ix + 1).copied()].into_iter().flatten() {
                let c = placed[ya][xa];
                if c == ' ' || placed[yb][xb] != c {
                    continue;
                }
                let steps = (yb - ya).max(xa.abs_diff(xb));
                for k in 1..steps {
                    let y = ya + (yb - ya) * k / steps;
                    let x = if xb > xa { xa + (xb - xa) * k / steps } else { xa - (xa - xb) * k / steps };
                    if g[y][x] == ' ' {
                        g[y][x] = c;
                    }
                }
            }
        }
    }
    g.into_iter().map(|r| r.into_iter().collect()).collect()
}

fn shaped(v: &mut Value, count: i64) {
    let Some(pattern) = v["pattern"].as_array() else { return };
    let rows = trimmed(pattern);
    let (h, w) = (rows.len(), rows.first().map_or(0, Vec::len));
    if h == 0 || w > 3 || h > 3 {
        return;
    }
    // Nine of one thing into one, the way metal goes into a block: a conversion, not something made.
    let one = rows[0][0];
    if w == 3 && h == 3 && count == 1 && one != ' ' && rows.iter().flatten().all(|c| *c == one) {
        return;
    }
    // How many cells each ingredient takes, for the cells grown between two different ones.
    let mut tally: Vec<(char, usize)> = Vec::new();
    for c in rows.iter().flatten().filter(|c| **c != ' ') {
        match tally.iter_mut().find(|(k, _)| k == c) {
            Some(t) => t.1 += 1,
            None => tally.push((*c, 1)),
        }
    }
    let out: Vec<Value> = grow(&rows, &tally).into_iter().map(Value::String).collect();
    v["pattern"] = Value::Array(out);
}

fn shapeless(v: &mut Value, count: i64) {
    let Some(list) = v["ingredients"].as_array().cloned() else { return };
    let n = list.len();
    if n == 0 || n >= 10 {
        return;
    }
    // One item into nine or more: the other half of a conversion.
    if n == 1 && count >= 9 {
        return;
    }
    if n <= 2 {
        let (a, b) = (list[0].clone(), list[n - 1].clone());
        let mut key = Map::new();
        key.insert("A".into(), a);
        key.insert("B".into(), b);
        if let Some(fields) = v.as_object_mut() {
            fields.remove("ingredients");
            fields.insert("type".into(), json!("minecraft:crafting_shaped"));
            fields.insert("key".into(), Value::Object(key));
            fields.insert("pattern".into(), json!(if n == 1 { ["A", "A", "A", "A"] } else { ["A", "A", "B", "B"] }));
        }
        return;
    }
    let times = 10usize.div_ceil(n);
    let more: Vec<Value> = std::iter::repeat_n(list, times).flatten().collect();
    v["ingredients"] = Value::Array(more);
}

pub fn rewrite(recipe_id: &str, recipe: &mut Value) {
    let kind = recipe["type"].as_str().unwrap_or("").to_owned();
    if !matches!(kind.as_str(), "minecraft:crafting_shaped" | "minecraft:crafting_shapeless") {
        return;
    }
    let result = &recipe["result"];
    let (id, count) = match result.as_str() {
        Some(id) => (id.to_owned(), 1),
        None => (result["id"].as_str().unwrap_or("").to_owned(), result["count"].as_i64().unwrap_or(1)),
    };
    // Wood goes less far: a log makes 2 planks, and 2 planks make 2 sticks.
    if count == 4 && (id == "minecraft:stick" || (id.ends_with("_planks") && kind == "minecraft:crafting_shapeless")) && result.is_object() {
        recipe["result"]["count"] = json!(2);
    }
    let qualified = if recipe_id.contains(':') { recipe_id.to_owned() } else { format!("minecraft:{recipe_id}") };
    if early(&id) || EARLY.binary_search(&qualified.as_str()).is_ok() {
        return;
    }
    if kind == "minecraft:crafting_shaped" {
        shaped(recipe, count);
    } else {
        shapeless(recipe, count);
    }
}
